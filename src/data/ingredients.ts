// profile order: sweet, sour, bitter, strong, fresh, aromatic
type P = [number, number, number, number, number, number];

const l = (tr: string, en: string): L => ({ tr, en });

function ing(
  id: string,
  name: L,
  category: IngredientCategory,
  chem: { abv?: number; sugar?: number; acid?: number },
  color: string,
  p: P,
  origin: L,
  notes: [L, L, L],
  story: L,
  extra: Partial<Ingredient> = {},
): Ingredient {
  return {
    id,
    name,
    category,
    abv: chem.abv ?? 0,
    sugar: chem.sugar ?? 0,
    acid: chem.acid ?? 0,
    color,
    profile: { sweet: p[0], sour: p[1], bitter: p[2], strong: p[3], fresh: p[4], aromatic: p[5] },
    origin,
    notes: { nose: notes[0], palate: notes[1], finish: notes[2] },
    story,
    ...extra,
  };
}

