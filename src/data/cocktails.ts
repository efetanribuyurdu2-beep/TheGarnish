function c(
  id: string,
  name: L,
  world: WorldId | "all",
  root: Root,
  glass: Glass,
  ice: Ice,
  method: Method,
  garnish: string,
  parts: [string, number, boolean?][],
  origin: L,
  story: L,
  moods: Mood[],
  extra: Partial<Cocktail> = {},
): Cocktail {
  const p: Part[] = parts.map(([id, ml, top]) => ({ id, ml, ...(top ? { top: true } : {}) }));
  return { id, name, world, root, glass, ice, method, garnish, parts: p, origin, story, moods, ...extra };
}

