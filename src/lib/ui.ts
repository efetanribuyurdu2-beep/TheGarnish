export type UIKey = keyof typeof dict;
export const tr = (lang: Lang, key: UIKey, vars?: Record<string, string | number>) => {
  let s: string = dict[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
};

